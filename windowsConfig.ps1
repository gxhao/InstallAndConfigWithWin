    $supportedMonitors = @(
        Get-ChildItem -LiteralPath $monitorDataStorePath -ErrorAction SilentlyContinue |
            Where-Object {
                $monitorSettings = Get-ItemProperty -LiteralPath $_.PSPath -Name 'AutoColorManagementSupported' -ErrorAction SilentlyContinue
                $null -ne $monitorSettings -and [int]$monitorSettings.AutoColorManagementSupported -eq 1
            }
    )

    foreach ($monitor in $supportedMonitors) {
        New-ItemProperty -LiteralPath $monitor.PSPath -Name 'AutoColorManagementEnabled' -Value 1 -PropertyType DWord -Force | Out-Null
    }

    if ($supportedMonitors.Count -gt 0) {
        Write-Host "Enabled automatic color management for $($supportedMonitors.Count) supported display(s)." -ForegroundColor Green
    } else {
        Write-Host "No display reporting automatic color management support was found; skipped this setting." -ForegroundColor Yellow
    }
} else {
